#!/usr/bin/env python3
"""Build the tile -> target table from the game map file.

  python3 tools/build_targets.py MapExCe.bin            # writes src/wr_targets.h and out/wheel_region_targets.bin
  python3 tools/build_targets.py --from-bin targets.bin  # re-encode an existing 96,800-byte table

MapExCe.bin: u32 tile count (48400 = 220 x 220), then 16 bytes per tile:
  [u32 tile id (= row*220 + col), u16 terrain, u16 region, ...]
terrain: 15 village, 16 city, 17 gate, 18 port.

Target of a region = its village/port tile; a region without one uses its city or gate
(the tile closest to the centre of that city/gate). Tiles with region 0 get 0xFFFF.

src/wr_targets.h stores the table as runs (len u8, value u16 little endian) so it can be
compiled into a host mod without any extra file. A user patch that changes the map only
needs this tool run again (or the .bin placed next to the DLL, see README).
"""
import collections, os, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TILES = 48400


def from_map(path):
    d = open(path, 'rb').read()
    n = struct.unpack_from('<I', d, 0)[0]
    if n != TILES:
        sys.exit('unexpected tile count %d' % n)
    tiles = [struct.unpack_from('<IHH', d, 4 + i * 16) for i in range(n)]
    by_region = collections.defaultdict(lambda: collections.defaultdict(list))
    for tid, ter, reg in tiles:
        if reg and ter in (15, 16, 17, 18):
            by_region[reg][ter].append(tid)

    def centre(ts):
        mr = sum(t // 220 for t in ts) / len(ts)
        mc = sum(t % 220 for t in ts) / len(ts)
        return min(ts, key=lambda t: ((t // 220 - mr) ** 2 + (t % 220 - mc) ** 2, t))

    target, kinds = {}, collections.Counter()
    for reg, terr in by_region.items():
        for ter in (15, 18, 16, 17):
            if terr.get(ter):
                target[reg] = centre(terr[ter])
                kinds[ter] += 1
                break
    regions = {reg for _, _, reg in tiles if reg}
    print('regions %d, with target %d (village %d, port %d, city %d, gate %d), without %s' % (
        len(regions), len(target), kinds[15], kinds[18], kinds[16], kinds[17], sorted(regions - set(target))[:20]))
    return [target.get(reg, 0xFFFF) if reg else 0xFFFF for _, _, reg in tiles]


def encode(table):
    runs, prev, n = [], None, 0
    for v in table:
        if v == prev and n < 255:
            n += 1
        else:
            if prev is not None:
                runs.append((n, prev))
            prev, n = v, 1
    runs.append((n, prev))
    out = bytearray()
    for n, v in runs:
        out += bytes((n, v & 0xFF, v >> 8))
    return bytes(out)


def decode(blob):
    t = []
    for i in range(0, len(blob), 3):
        t += [blob[i + 1] | blob[i + 2] << 8] * blob[i]
    return t


def main():
    a = sys.argv[1:]
    if len(a) == 2 and a[0] == '--from-bin':
        raw = open(a[1], 'rb').read()
        if len(raw) != TILES * 2:
            sys.exit('expected %d bytes' % (TILES * 2))
        table = list(struct.unpack('<%dH' % TILES, raw))
    elif len(a) == 1:
        table = from_map(a[0])
    else:
        sys.exit(__doc__)
    blob = encode(table)
    assert decode(blob) == table
    os.makedirs(os.path.join(ROOT, 'out'), exist_ok=True)
    open(os.path.join(ROOT, 'out', 'wheel_region_targets.bin'), 'wb').write(struct.pack('<%dH' % TILES, *table))
    lines = ['/* GENERATED by tools/build_targets.py - tile -> target tile, runs of (len u8, value u16le). */',
             '#ifndef WR_TARGETS_H', '#define WR_TARGETS_H', '',
             '#define WR_TARGET_RUN_BYTES %du' % len(blob),
             '#define WR_TARGET_MAPPED %du  /* tiles that have a target */' % sum(v != 0xFFFF for v in table),
             '', 'static const unsigned char WR_TARGET_RUNS[WR_TARGET_RUN_BYTES] = {']
    for i in range(0, len(blob), 24):
        lines.append('    ' + ','.join('%d' % b for b in blob[i:i + 24]) + ',')
    lines += ['};', '', '#endif']
    open(os.path.join(ROOT, 'src', 'wr_targets.h'), 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote src/wr_targets.h (%d run bytes, %d mapped tiles) and out/wheel_region_targets.bin' % (
        len(blob), sum(v != 0xFFFF for v in table)))


if __name__ == '__main__':
    main()
