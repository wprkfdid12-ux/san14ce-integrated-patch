#!/usr/bin/env python3
"""Assemble src/wr_block.S and write src/wr_block.h (bytes + offsets).

Needs llvm-mc (or clang) and objcopy/nm from binutils or LLVM.
Usage: python3 tools/gen_block.py
"""
import os, re, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src', 'wr_block.S')
OUT = os.path.join(ROOT, 'src', 'wr_block.h')

FIELDS = ['d_flag', 'd_kfilter', 'd_ahits', 'd_bhits', 'd_khits', 'd_kcalls', 'd_table', 'd_pmap',
          'd_pdb', 'd_textlo', 'd_texthi', 'd_retb', 'stub_a', 'stub_b', 'stub_k', 'wr_block_end']


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit('failed: %s\n%s' % (' '.join(cmd), r.stderr))
    return r.stdout


def main():
    with tempfile.TemporaryDirectory() as t:
        obj = os.path.join(t, 'b.o')
        binf = os.path.join(t, 'b.bin')
        run(['llvm-mc', '-triple=x86_64-unknown-linux-gnu', '-filetype=obj', SRC, '-o', obj])
        relocs = run(['llvm-readobj', '-r', obj])
        if re.search(r'R_X86_64', relocs):
            sys.exit('block must not contain relocations:\n' + relocs)
        run(['objcopy', '-O', 'binary', '-j', '.text', obj, binf])
        data = open(binf, 'rb').read()
        syms = {}
        for line in run(['nm', obj]).splitlines():
            parts = line.split()
            if len(parts) == 3:
                syms[parts[2]] = int(parts[0], 16)
    missing = [f for f in FIELDS if f not in syms]
    if missing:
        sys.exit('missing symbols: %s' % missing)
    size = syms['wr_block_end']
    data = data[:size]
    lines = ['/* GENERATED by tools/gen_block.py from src/wr_block.S - do not edit by hand. */',
             '#ifndef WR_BLOCK_H', '#define WR_BLOCK_H', '']
    for f in FIELDS:
        if f == 'wr_block_end':
            continue
        lines.append('#define WR_OFF_%s 0x%03Xu' % (f.upper().replace('D_', '', 1) if f.startswith('d_') else f.upper(), syms[f]))
    lines.append('#define WR_BLOCK_SIZE 0x%03Xu' % size)
    lines.append('')
    lines.append('static const unsigned char WR_BLOCK[WR_BLOCK_SIZE] = {')
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join('0x%02X' % b for b in data[i:i + 16]) + ',')
    lines.append('};')
    lines.append('')
    lines.append('#endif')
    open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote %s (%d bytes)' % (OUT, size))


if __name__ == '__main__':
    main()
