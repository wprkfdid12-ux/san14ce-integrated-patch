#!/usr/bin/env python3
"""Assemble src/dl_block.S and write src/dl_block.h (bytes + offsets).

Needs llvm-mc (or clang) and objcopy/nm from binutils or LLVM.
Usage: python3 tools/gen_block.py
"""
import os, re, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src', 'dl_block.S')
OUT = os.path.join(ROOT, 'src', 'dl_block.h')

FIELDS = ['d_on','d_max','d_min','d_limit','d_orders','d_filled','d_seln','d_opens','d_multi','d_xhits','d_learned','d_stops','d_fails','d_skips','d_pmax','d_plimit','d_npers','d_popens','d_pmulti','d_qhits','d_unhid','d_fskip','d_cmd','d_first_ret','d_sel_person','f_valid','f_orders','f_slot','f_learn','f_tid','f_fid','f_pspec','f_pform','f_gidx','p_db','p_cost','p_head','p_cnt','p_npool','r_s','r_x','r_y','r_p','r_q','r_d','r_en','p_lock','f_fix','f_r1','f_r2','r_r1','r_r2','f_r3','r_r3','d_gems','d_persons','stub_s','stub_x','stub_y','stub_p','stub_q','stub_d','stub_r1','stub_r2','stub_r3','dl_block_end']


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit('failed: %s\n%s' % (' '.join(cmd), r.stderr))
    return r.stdout


def main():
    with tempfile.TemporaryDirectory() as t:
        obj = os.path.join(t, 'b.o')
        binf = os.path.join(t, 'b.bin')
        run(['llvm-mc', '-triple=x86_64-unknown-linux-gnu', '-filetype=obj', SRC, '-o', obj])
        relocs = run(['llvm-readobj', '-r', obj])
        if re.search(r'R_X86_64', relocs):
            sys.exit('block must not contain relocations:\n' + relocs)
        run(['objcopy', '-O', 'binary', '-j', '.text', obj, binf])
        data = open(binf, 'rb').read()
        syms = {}
        for line in run(['nm', obj]).splitlines():
            parts = line.split()
            if len(parts) == 3:
                syms[parts[2]] = int(parts[0], 16)
    missing = [f for f in FIELDS if f not in syms]
    if missing:
        sys.exit('missing symbols: %s' % missing)
    size = syms['dl_block_end']
    data = data[:size]
    lines = ['/* GENERATED by tools/gen_block.py from src/dl_block.S - do not edit by hand. */',
             '#ifndef DL_BLOCK_H', '#define DL_BLOCK_H', '']
    for f in FIELDS:
        if f == 'dl_block_end':
            continue
        lines.append('#define DL_OFF_%s 0x%03Xu' % (f.upper()[2:] if f.startswith('d_') else f.upper(), syms[f]))
    lines.append('#define DL_BLOCK_SIZE 0x%03Xu' % size)
    lines.append('')
    lines.append('static const unsigned char DL_BLOCK[DL_BLOCK_SIZE] = {')
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join('0x%02X' % b for b in data[i:i + 16]) + ',')
    lines.append('};')
    lines.append('')
    lines.append('#endif')
    open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote %s (%d bytes)' % (OUT, size))


if __name__ == '__main__':
    main()
